/**
 * Pre-PR evidence pipeline: compares the working branch against upstream and
 * regenerates FIXES.md from scratch - no manual mapping.
 *
 *   npm run report:fixes [-- options]
 *
 * 1. Runs the e2e suite twice, against upstream's cp/ and the branch's cp/,
 *    each in a throwaway `git worktree` on a private port (the shared working
 *    tree is never touched).
 * 2. Sends the code diff (`git diff merge-base..head -- cp/`), the tests whose
 *    outcome changed (with upstream's failure messages) and the commit messages
 *    (as hints) to Claude via the headless `claude` CLI. Claude identifies each
 *    distinct fix from the code and explains problem / root cause / change, and
 *    assigns the fail->pass tests that evidence it.
 * 3. Validates that answer against the real results (unknown test titles are
 *    dropped, unassigned fail->pass tests and regressions are flagged), saves
 *    it to docs/fixes/analysis.json, and writes FIXES.md with a before/after
 *    test table and screenshot pair per fix.
 *
 * Options:
 *   --head <ref>          branch under review (default: paste-handling-fixes if
 *                         it exists, else HEAD)
 *   --base <ref>          upstream ref (default: upstream/master). "Before" is
 *                         merge-base(base, head), as a PR diff shows.
 *   --harness <ref>       ref whose e2e-tests/ runs both passes (default: HEAD;
 *                         PR branches carry cp/ only)
 *   --title <text>        FIXES.md heading
 *   --model <name>        model for the analysis (default: the CLI's default)
 *   --analysis <file>     reuse a saved analysis.json instead of calling Claude.
 *                         Suites still run (fresh evidence, no claude CLI needed);
 *                         add --from-runs to also skip the runs (pure re-render)
 *   --out <file>          markdown output (default: FIXES.md at the repo root)
 *   --images <dir>        screenshot + analysis dir (default: docs/fixes)
 *   --image-base-url <u>  image link prefix (default: raw.githubusercontent.com
 *                         for origin's master, so FIXES.md can be pasted into a
 *                         PR description; images must be pushed to master)
 *   --relative-images     link images relative to --out instead
 *   --from-runs <b> <a>   skip running; reuse two test-report dirs (before, after)
 *   --keep-runs <dir>     keep raw run outputs under <dir>/before|after
 *   --pdf                 also preserve runs to test-report-upstream/ and
 *                         test-report-fork/ and render the PDF report
 *   --no-fetch            do not `git fetch` the base remote first
 *   --force               overwrite an --out file this script did not generate
 *
 * Exit codes: 0 ok, 1 setup error, 2 report written with regressions.
 * Components are taken from COMMITTED refs - commit head changes first.
 */
const { execSync, execFileSync, spawnSync } = require("child_process");
const fs = require("fs");
const net = require("net");
const os = require("os");
const path = require("path");

const E2E = path.resolve(__dirname, "..");
const REPO = path.resolve(E2E, "..");
const MARKER = "<!-- generated by e2e-tests/report/make-fixes-md.js -->";
const ENGINE_ORDER = ["chromium", "firefox", "webkit"];
const MAX_DIFF_CHARS = 400000;

// ---------- args ----------

function parseArgs(argv) {
  const o = { out: "FIXES.md", images: path.join("docs", "fixes"), fetch: true };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    const next = () => {
      if (i + 1 >= argv.length) throw new Error(`${a} needs a value`);
      return argv[++i];
    };
    switch (a) {
      case "--head": o.head = next(); break;
      case "--base": o.base = next(); break;
      case "--harness": o.harness = next(); break;
      case "--title": o.title = next(); break;
      case "--model": o.model = next(); break;
      case "--analysis": o.analysis = path.resolve(process.cwd(), next()); break;
      case "--out": o.out = next(); break;
      case "--images": o.images = next(); break;
      case "--image-base-url": o.imageBaseUrl = next(); break;
      case "--relative-images": o.relativeImages = true; break;
      case "--from-runs": o.fromRuns = [next(), next()]; break;
      case "--keep-runs": o.keepRuns = next(); break;
      case "--pdf": o.pdf = true; break;
      case "--no-fetch": o.fetch = false; break;
      case "--force": o.force = true; break;
      case "-h":
      case "--help":
        console.log(fs.readFileSync(__filename, "utf-8").match(/\/\*\*([\s\S]*?)\*\//)[1].replace(/^ \* ?/gm, ""));
        process.exit(0);
      default:
        throw new Error(`Unknown option: ${a} (see --help)`);
    }
  }
  return o;
}

// ---------- git ----------

function git(args, opts = {}) {
  const out = execFileSync("git", args, { cwd: REPO, encoding: "utf-8", maxBuffer: 64 * 1024 * 1024, ...opts });
  return out == null ? "" : out.trim();
}

function revParse(ref) {
  try {
    return git(["rev-parse", "--verify", "--quiet", `${ref}^{commit}`], { stdio: ["ignore", "pipe", "ignore"] });
  } catch (e) {
    return null;
  }
}

function commitLog(fromSha, toSha) {
  return git(["log", "--no-merges", "--reverse", "--format=## %h %s%n%b", `${fromSha}..${toSha}`, "--", "cp/"])
    .split("\n")
    .filter((l) => !/^(Co-Authored-By|Signed-off-by):/i.test(l.trim()))
    .join("\n");
}

// ---------- isolated suite run ----------

function freePort() {
  return new Promise((resolve, reject) => {
    const srv = net.createServer();
    srv.unref();
    srv.on("error", reject);
    srv.listen(0, () => {
      const { port } = srv.address();
      srv.close(() => resolve(port));
    });
  });
}

/**
 * Runs <harnessSha>'s e2e-tests/ against <componentSha>'s cp/ in a temporary
 * worktree; copies test-report/ out to <runsRoot>/<label> before removing it.
 */
async function runIsolated(label, harnessSha, componentSha, runsRoot) {
  const wt = fs.mkdtempSync(path.join(os.tmpdir(), `rte-fixes-${label}-`));
  fs.rmSync(wt, { recursive: true, force: true }); // git worktree add wants a fresh path
  console.log(`\n=== [${label}] cp/ @ ${componentSha.slice(0, 8)}, suite @ ${harnessSha.slice(0, 8)} ===`);
  git(["worktree", "add", "--detach", "--quiet", wt, harnessSha]);
  try {
    const wtE2E = path.join(wt, "e2e-tests");
    if (!fs.existsSync(path.join(wtE2E, "playwright.config.js"))) {
      throw new Error(`--harness ${harnessSha.slice(0, 8)} has no e2e-tests/playwright.config.js`);
    }
    fs.rmSync(path.join(wt, "cp"), { recursive: true, force: true });
    execSync(`git archive ${componentSha} cp | tar -x -C "${wt}"`, { cwd: REPO, stdio: ["ignore", "ignore", "inherit"] });
    fs.symlinkSync(path.join(E2E, "node_modules"), path.join(wtE2E, "node_modules"), "dir");

    // Same suite, private port, never reuse a running server, quiet output
    const port = await freePort();
    const wrapper = path.join(wtE2E, "playwright.fixes.config.js");
    fs.writeFileSync(
      wrapper,
      `const base = require("./playwright.config.js");
module.exports = {
  ...base,
  reporter: [["dot"], ["./report/paste-report.js"]],
  use: { ...base.use, baseURL: "http://localhost:${port}" },
  webServer: { ...base.webServer, port: ${port}, reuseExistingServer: false, env: { ...process.env, PORT: "${port}" } },
};
`
    );
    // Failures are expected on the "before" pass - only a missing report is fatal
    const res = spawnSync("npx", ["playwright", "test", "--config", wrapper], { cwd: wtE2E, stdio: ["ignore", "ignore", "inherit"] });
    if (res.error) throw res.error;
    const report = path.join(wtE2E, "test-report");
    if (!fs.existsSync(path.join(report, "results.json"))) throw new Error(`[${label}] run produced no test-report/results.json`);
    const dest = path.join(runsRoot, label);
    fs.rmSync(dest, { recursive: true, force: true });
    fs.cpSync(report, dest, { recursive: true });
    const c = JSON.parse(fs.readFileSync(path.join(dest, "results.json"), "utf-8")).counts;
    console.log(`[${label}] ${c.passed} passed, ${c.failed} failed, ${c.skipped} skipped`);
    return dest;
  } finally {
    try {
      git(["worktree", "remove", "--force", wt]);
    } catch (e) {
      console.warn(`Could not remove worktree ${wt} - run \`git worktree prune\` later.`);
    }
  }
}

// ---------- results ----------

/** Scenarios keyed by unique test title, with per-engine entries. */
function loadRun(dir) {
  const data = JSON.parse(fs.readFileSync(path.join(dir, "results.json"), "utf-8"));
  const byTitle = new Map();
  for (const e of data.entries) {
    if (!byTitle.has(e.title)) byTitle.set(e.title, { file: e.file, title: e.title, projects: {} });
    byTitle.get(e.title).projects[e.project] = e;
  }
  return { dir, data, byTitle };
}

const isFail = (s) => s !== "passed" && s !== "skipped";

function overall(projects) {
  const st = Object.values(projects || {}).map((e) => e.status);
  if (!st.length) return "absent";
  if (st.some(isFail)) return "failed";
  if (st.every((s) => s === "skipped")) return "skipped";
  return "passed";
}

function statusCell(projects) {
  const s = overall(projects);
  const icon = { passed: "✅ pass", failed: "❌ fail", skipped: "⏭️ skip", absent: "— not run" }[s];
  if (s !== "failed") return icon;
  const failing = Object.keys(projects).filter((p) => isFail(projects[p].status));
  return failing.length === Object.keys(projects).length ? icon : `${icon} (${failing.join(", ")})`;
}

function firstError(projects) {
  for (const e of Object.values(projects || {})) {
    if (e.error) return e.error.split("\n").filter((l) => l.trim()).slice(0, 3).join(" ").slice(0, 300);
  }
  return "";
}

/** Prefer an engine whose outcome changed, Chromium first. */
function pickEngine(b, a) {
  const engines = Object.keys(a || b || {});
  const changed = engines.filter((p) => ((b || {})[p] || {}).status !== ((a || {})[p] || {}).status);
  for (const list of [changed, engines]) {
    for (const p of ENGINE_ORDER) if (list.includes(p)) return p;
    if (list.length) return list[0];
  }
  return null;
}

// ---------- analysis (Claude, headless) ----------

const ANALYSIS_SCHEMA = {
  type: "object",
  properties: {
    fixes: {
      type: "array",
      items: {
        type: "object",
        properties: {
          title: { type: "string" },
          problem: { type: "string" },
          cause: { type: "string" },
          change: { type: "string" },
          code: { type: "array", items: { type: "string" } },
          tests: { type: "array", items: { type: "string" } },
          shot: { type: ["string", "null"] },
        },
        required: ["title", "problem", "cause", "change", "code", "tests", "shot"],
      },
    },
    otherChanges: { type: "array", items: { type: "string" } },
  },
  required: ["fixes", "otherChanges"],
};

const SYSTEM_PROMPT =
  "You review pull requests for an Appian rich text editor component built on Summernote. " +
  "You explain code changes to reviewers precisely and factually, deriving every claim from the diff.";

function buildPrompt({ base, head, diff, log, fixed, regressed, stillFailing }) {
  const list = (rows, withError) =>
    rows.length ? rows.map((r) => `- ${r.title}  [${r.file}]${withError && r.error ? `\n    upstream failure: ${r.error}` : ""}`).join("\n") : "(none)";
  return `Pull request: \`${head}\` into \`${base}\`.

The same browser test suite was run against the component before (upstream) and after (this branch).

## Tests that FAIL on upstream and PASS on this branch
${list(fixed, true)}

## Tests that PASS on upstream and FAIL on this branch (regressions)
${list(regressed, false)}

## Tests failing on both
${list(stillFailing, false)}

## Commit messages (hints only - may be incomplete, outdated or empty; the diff is authoritative)
${log || "(none)"}

## Code diff (upstream -> this branch, cp/ only)
\`\`\`diff
${diff}
\`\`\`

## Task
Identify every distinct BEHAVIORAL fix this diff makes. For each one:
- title: the user-visible symptom that was fixed, sentence case, under 12 words.
- problem: what users experienced on upstream (1-3 sentences, no code jargon).
- cause: the root cause in the upstream code - name the functions, regexes or conditions involved.
- change: what the new code does and why it fixes the cause - name the functions involved.
- code: the functions or code areas changed for this fix.
- tests: EXACT titles, copied verbatim from the "FAIL on upstream and PASS" list, that evidence this fix. Assign each of those tests to the single fix it best evidences; leave tests empty for a fix with no browser-level test (e.g. unit-tested only).
- shot: one title from this fix's tests whose end-state screenshot best shows the before/after difference, or null.

Order fixes by user impact, most severe first. Combine changes that address one symptom; split changes that address different symptoms. Put refactors, formatting, comment and test-only changes in otherChanges as one-line summaries. Do not describe behavior the diff does not support. Wrap code identifiers in backticks.`;
}

function analyze(o, input) {
  const args = [
    "-p", "--output-format", "json", "--tools", "", "--no-session-persistence",
    "--setting-sources", "", "--strict-mcp-config",
    "--system-prompt", SYSTEM_PROMPT,
    "--json-schema", JSON.stringify(ANALYSIS_SCHEMA),
  ];
  if (o.model) args.push("--model", o.model);
  console.log(`\nAnalyzing the diff with Claude${o.model ? ` (${o.model})` : ""}...`);
  const res = spawnSync("claude", args, { input: buildPrompt(input), encoding: "utf-8", maxBuffer: 64 * 1024 * 1024 });
  if (res.error) throw new Error(`Could not run the \`claude\` CLI: ${res.error.message}`);
  let out;
  try {
    out = JSON.parse(res.stdout);
  } catch (e) {
    throw new Error(`claude returned non-JSON output (exit ${res.status}):\n${(res.stdout || res.stderr).slice(0, 2000)}`);
  }
  if (out.is_error || !out.structured_output) throw new Error(`Analysis failed: ${String(out.result || out.subtype).slice(0, 2000)}`);
  console.log(`Analysis: ${out.structured_output.fixes.length} fixes ($${(out.total_cost_usd || 0).toFixed(2)})`);
  return out.structured_output;
}

// ---------- markdown helpers ----------

function mdEsc(s) {
  return String(s).replace(/\|/g, "\\|").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

/** Escape HTML outside `code spans`, so prose like "<img> tags" is not rendered. */
function prose(s) {
  return String(s)
    .split(/(`[^`]*`)/)
    .map((part, i) => (i % 2 ? part : part.replace(/</g, "&lt;").replace(/>/g, "&gt;")))
    .join("");
}

function slug(s) {
  return String(s).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 60);
}

// ---------- main ----------

async function main() {
  const o = parseArgs(process.argv.slice(2));
  const base = o.base || "upstream/master";
  const head = o.head || (revParse("paste-handling-fixes") ? "paste-handling-fixes" : "HEAD");

  if (o.fetch && !o.fromRuns) {
    const remote = base.includes("/") ? base.split("/")[0] : null;
    if (remote && git(["remote"]).split("\n").includes(remote)) {
      console.log(`Fetching ${remote}...`);
      git(["fetch", "--quiet", remote], { stdio: ["ignore", "ignore", "inherit"] });
    }
  }
  const headSha = revParse(head);
  const baseSha = revParse(base);
  const harnessSha = revParse(o.harness || "HEAD");
  if (!headSha || !baseSha || !harnessSha) throw new Error(`Cannot resolve ${[!headSha && head, !baseSha && base, !harnessSha && o.harness].filter(Boolean).join(", ")}`);
  const beforeSha = git(["merge-base", baseSha, headSha]);

  const diff = git(["diff", beforeSha, headSha, "--", "cp/"]);
  if (!diff) throw new Error(`No cp/ changes between ${base} and ${head}.`);
  if (diff.length > MAX_DIFF_CHARS && !o.analysis) throw new Error(`cp/ diff is ${diff.length} chars - too large to analyze in one pass.`);

  const outPath = path.resolve(REPO, o.out);
  if (fs.existsSync(outPath) && !o.force && !fs.readFileSync(outPath, "utf-8").startsWith(MARKER)) {
    console.error(`${o.out} exists and was not generated by this script - pass --force to replace it.`);
    process.exit(1);
  }

  // 1. Runs
  let beforeDir, afterDir, tmpRuns;
  if (o.fromRuns) {
    [beforeDir, afterDir] = o.fromRuns.map((d) => path.resolve(process.cwd(), d));
  } else {
    const runsRoot = o.keepRuns ? path.resolve(process.cwd(), o.keepRuns) : (tmpRuns = fs.mkdtempSync(path.join(os.tmpdir(), "rte-fixes-runs-")));
    fs.mkdirSync(runsRoot, { recursive: true });
    beforeDir = await runIsolated("before", harnessSha, beforeSha, runsRoot);
    afterDir = await runIsolated("after", harnessSha, headSha, runsRoot);
  }
  const before = loadRun(beforeDir);
  const after = loadRun(afterDir);

  // Classify per unique test title (upstream's per-execution counts wobble)
  const fixed = [], regressed = [], stillFailing = [];
  for (const [t, a] of after.byTitle) {
    const bp = (before.byTitle.get(t) || {}).projects || {};
    const row = { title: t, file: a.file, b: bp, a: a.projects, error: firstError(bp) };
    const sb = overall(bp), sa = overall(a.projects);
    if (sb === "failed" && sa === "passed") fixed.push(row);
    else if (sb !== "failed" && sa === "failed") regressed.push(row);
    else if (sb === "failed" && sa === "failed") stillFailing.push(row);
  }

  // 2. Analysis
  const imagesDir = path.resolve(REPO, o.images);
  fs.mkdirSync(imagesDir, { recursive: true });
  const analysis = o.analysis
    ? JSON.parse(fs.readFileSync(o.analysis, "utf-8"))
    : analyze(o, { base, head, diff, log: commitLog(beforeSha, headSha), fixed, regressed, stillFailing });

  // 3. Validate against the real results
  const problems = [];
  const fixedByTitle = new Map(fixed.map((r) => [r.title, r]));
  const claimed = new Set();
  const fixes = analysis.fixes.map((f) => {
    const rows = [];
    for (const t of f.tests || []) {
      const row = fixedByTitle.get(t);
      if (!row) {
        problems.push(`Analysis cited a test that did not go fail -> pass, ignored: "${t}"`);
        continue;
      }
      if (claimed.has(t)) continue;
      claimed.add(t);
      rows.push(row);
    }
    const shot = rows.find((r) => r.title === f.shot) || rows[0] || null;
    return { ...f, rows, shotRow: shot };
  });
  for (const r of fixed) if (!claimed.has(r.title)) problems.push(`Fail -> pass test not attributed to any fix: "${r.title}"`);
  for (const r of regressed) problems.push(`REGRESSION: "${r.title}" passes on ${base} but fails on ${head}`);
  fs.writeFileSync(path.join(imagesDir, "analysis.json"), JSON.stringify(analysis, null, 2) + "\n");

  if (o.pdf) {
    for (const [src, name] of [[beforeDir, "test-report-upstream"], [afterDir, "test-report-fork"]]) {
      const dest = path.join(E2E, name);
      if (path.resolve(src) === dest) continue;
      fs.rmSync(dest, { recursive: true, force: true });
      fs.cpSync(src, dest, { recursive: true });
    }
    const r = spawnSync("node", [path.join(__dirname, "make-before-after.js"), "--analysis", path.join(imagesDir, "analysis.json")], { cwd: E2E, stdio: "inherit" });
    if (r.status) console.error("PDF render failed.");
  }

  // 4. Screenshots, named after the exemplar test so names stay stable run to run
  let imageBase = o.imageBaseUrl;
  if (!imageBase && !o.relativeImages) {
    const m = git(["remote", "get-url", "origin"]).match(/github\.com[:/](.+?)(?:\.git)?$/);
    if (m) imageBase = `https://raw.githubusercontent.com/${m[1]}/master`;
  }
  const link = (abs) =>
    imageBase
      ? `${imageBase.replace(/\/$/, "")}/${path.relative(REPO, abs).split(path.sep).join("/")}`
      : path.relative(path.dirname(outPath), abs).split(path.sep).join("/");
  let shotsWritten = 0;
  function shotPair(row) {
    if (!row) return "";
    const engine = pickEngine(row.b, row.a);
    const copy = (run, projects, side) => {
      const e = projects[engine];
      const src = e && e.screenshots && e.screenshots[0] && path.join(run.dir, e.screenshots[0]);
      if (!src || !fs.existsSync(src)) return null;
      const dest = path.join(imagesDir, `${slug(row.title)}-${side}.png`);
      fs.copyFileSync(src, dest);
      shotsWritten++;
      return link(dest);
    };
    const bi = copy(before, row.b, "before"), ai = copy(after, row.a, "after");
    if (!bi && !ai) return "";
    const cell = (img, alt) => (img ? `![${alt}](${img})` : "_no screenshot_");
    return `_Screenshot (${engine}): ${mdEsc(row.title)}_\n\n| Before (upstream) | After (this branch) |\n|---|---|\n| ${cell(bi, "before")} | ${cell(ai, "after")} |\n\n`;
  }

  // 5. Markdown
  const short = (sha) => sha.slice(0, 7);
  const changedFiles = git(["diff", "--name-only", beforeSha, headSha, "--", "cp/"]).split("\n").filter(Boolean);
  const engines = [...new Set(after.data.entries.map((e) => e.project))];
  let md = `${MARKER}\n<!-- Regenerate on master: cd e2e-tests && npm run report:fixes -->\n\n`;
  md += `# ${o.title || `Fixes in \`${head}\``}\n\n`;
  md += `Changes in \`${head}\` (\`${short(headSha)}\`) relative to \`${base}\` (\`${short(beforeSha)}\`), confined to:\n\n`;
  md += changedFiles.map((f) => `- \`${f}\``).join("\n") + "\n\n";
  md += `Each fix below was identified from the code diff and verified by running the same browser test suite against both versions on the ${engines.join(", ")} engines; "before" is the behavior of the current upstream component.\n\n`;
  if (problems.length) md += `> [!WARNING]\n> Pipeline findings:\n${problems.map((p) => `> - ${mdEsc(p)}`).join("\n")}\n\n`;
  md += `---\n\n`;

  fixes.forEach((f, i) => {
    md += `## ${i + 1}. ${prose(f.title)}\n\n`;
    md += `**Before:** ${prose(f.problem)}\n\n`;
    md += `**Cause:** ${prose(f.cause)}\n\n`;
    md += `**Fix:** ${prose(f.change)}\n\n`;
    if (f.code && f.code.length) md += `**Code:** ${f.code.map((c) => (c.startsWith("`") ? c : `\`${c}\``)).join(", ")}\n\n`;
    if (f.rows.length) {
      md += `| Evidencing test | Before | After |\n|---|---|---|\n`;
      md += f.rows.map((r) => `| ${mdEsc(r.title)} | ${statusCell(r.b)} | ${statusCell(r.a)} |`).join("\n") + "\n\n";
    } else {
      md += `_No browser-level test covers this fix; see the unit tests under \`cp/tests/\`._\n\n`;
    }
    md += shotPair(f.shotRow);
  });

  if (analysis.otherChanges && analysis.otherChanges.length) {
    md += `### Other changes (no behavior change)\n\n${analysis.otherChanges.map((c) => `- ${prose(c)}`).join("\n")}\n\n`;
  }

  const count = (run) => [...run.byTitle.values()].filter((x) => overall(x.projects) === "failed").length;
  const bc = before.data.counts, ac = after.data.counts;
  md += `---\n\n### Verification\n\n`;
  md += `The identical browser test suite was run against \`${base}\` and \`${head}\`:\n\n`;
  md += `| | Upstream | This branch |\n|---|---|---|\n`;
  md += `| Test executions passing | ${bc.passed} | ${ac.passed} |\n`;
  md += `| Test executions failing | ${bc.failed} | ${ac.failed} |\n`;
  md += `| Scenarios failing (unique tests) | ${count(before)} | ${count(after)} |\n\n`;
  md += regressed.length
    ? `**${regressed.length} regression(s) found - see the warning above.**\n`
    : `No regressions: every scenario that passes on upstream also passes on this branch.\n`;

  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, md);
  if (tmpRuns) fs.rmSync(tmpRuns, { recursive: true, force: true });

  problems.forEach((p) => console.warn(`${p.startsWith("REGRESSION") ? "ERROR" : "WARNING"}: ${p}`));
  console.log(`\nWrote ${path.relative(REPO, outPath)}: ${fixes.length} fixes, ${shotsWritten} screenshots in ${path.relative(REPO, imagesDir)}/`);
  if (imageBase) console.log(`Image links point at ${imageBase} - commit and push ${path.relative(REPO, imagesDir)}/ to master before pasting.`);
  if (regressed.length) process.exitCode = 2;
}

main().catch((e) => {
  console.error(e.message || e);
  process.exit(1);
});
